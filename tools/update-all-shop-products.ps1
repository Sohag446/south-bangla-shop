# Verify that every mapped target exists on disk
Write-Host "Verifying target paths exist..."
$missingTargets = 0
foreach ($k in $map.Keys) {
    $t = $map[$k]
    if (-not (Test-Path $t)) {
        Write-Host "ERROR: Target path does not exist: $t (for $k)"
        $missingTargets++
    }
}

if ($missingTargets -gt 0) {
    Write-Host "Aborting due to missing target files!"
    exit 1
}

Write-Host "All $($map.Count) mapped target paths exist on disk! Proceeding to update data/shop-products.js..."

$file = "data/shop-products.js"
$lines = [System.IO.File]::ReadAllLines($file)
$updatedCount = 0
$currentId = ""

for ($i = 0; $i -lt $lines.Length; $i++) {
    $line = $lines[$i]
    if ($line -match '^\s+id:\s+"([^"]+)"') {
        $currentId = $Matches[1]
    }
    
    if ($currentId -and $map.ContainsKey($currentId)) {
        if ($line -match 'images:\s*\["(.*?)"\]') {
            $newImg = $map[$currentId]
            $lines[$i] = $line -replace 'images:\s*\["(.*?)"\]', "images: [`"$newImg`"]"
            $updatedCount++
            $currentId = "" # reset
        }
    }
}

[System.IO.File]::WriteAllLines($file, $lines)
Write-Host "Successfully updated $updatedCount products in $file!"
